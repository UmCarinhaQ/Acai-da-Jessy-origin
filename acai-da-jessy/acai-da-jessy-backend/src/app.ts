import express from "express";
import cors from "cors";
import helmet from "helmet";
import cookieParser from "cookie-parser";
import rateLimit from "express-rate-limit";
import auth from "./routes/auth";
import cardapio from "./routes/cardapio";
import pedidos from "./routes/pedidos";
import conta from "./routes/conta";
import admin from "./routes/admin";
import { tratarErro } from "./middlewares/tratarErro";
const app=express();
app.use(helmet());
app.use(cors({origin:process.env.FRONTEND_URL,credentials:true}));
app.use(express.json({limit:"1mb"}));
app.use(cookieParser());
app.use("/api/auth",rateLimit({windowMs:15*60*1000,limit:20,standardHeaders:true,legacyHeaders:false}));
app.get("/api/health",(_req,res)=>res.json({status:"online",sistema:"Açaí da Jessy API"}));
app.use("/api/auth",auth);
app.use("/api/cardapio",cardapio);
app.use("/api/pedidos",pedidos);
app.use("/api/conta",conta);
app.use("/api/admin",admin);
app.use((req,res)=>res.status(404).json({erro:"Rota não encontrada."}));
app.use(tratarErro);
export default app;